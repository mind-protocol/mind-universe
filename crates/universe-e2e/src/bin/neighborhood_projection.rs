//! Generate the desktop neighborhood projection with REAL layout positions.
//!
//! Runs the executed neighborhood arc (measured-semantic energy, N BehaviorBonds
//! executed) and lays the resulting nodes out with the REAL layout engine
//! (`universe_assets::layout::compute`, force-directed and energy-weighted), then
//! writes an app-friendly JSON that `neighborhood-fixture.ts` imports.
//!
//! So both are now real: the ENERGY is measured+executed, and the POSITIONS come
//! from the layout engine (not a hand-placed TS star). Regenerate with:
//!   cargo run -p universe-e2e --bin neighborhood_projection

use serde_json::json;
use std::{error::Error, fs, path::PathBuf, process};
use universe_assets::layout::{compute, LayoutInput, LayoutLink, LayoutNode, LayoutParams};
use universe_core::EntityKey;
use universe_e2e::neighborhood_arc::execute_neighborhood;

fn main() {
    if let Err(error) = run() {
        eprintln!("neighborhood_projection_failed: {error}");
        process::exit(1);
    }
}

fn run() -> Result<(), Box<dyn Error>> {
    let repository = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let artifact_root = repository.join("artifacts/neighborhood-projection/run");
    // Fresh store each run so the authority ChangeSet installs cleanly.
    let _ = fs::remove_dir_all(&artifact_root);

    let execution =
        execute_neighborhood(&repository, &artifact_root, 12).map_err(|error| format!("{error:?}"))?;
    let start = execution.arc.start;

    // Lay out the neighborhood with the real engine. Bond strength (hence
    // attraction) is the measured energy, so stronger relations sit closer.
    let max_energy = execution
        .arc
        .glides
        .iter()
        .map(|glide| glide.transfer_energy)
        .max()
        .unwrap_or(1)
        .max(1) as f64;
    let mut nodes = vec![LayoutNode::new(start)];
    let mut links = Vec::new();
    for glide in &execution.arc.glides {
        nodes.push(LayoutNode::new(glide.target));
        let strength = (glide.transfer_energy as f64 / max_energy).clamp(0.0, 1.0);
        let mut link = LayoutLink::generic(start, glide.target);
        link.polarity = [strength, strength];
        links.push(link);
    }
    let layout = compute(&LayoutInput {
        nodes,
        links,
        params: LayoutParams::default(),
    })?;
    let position = |key: EntityKey| layout.position(key).unwrap_or([0.0, 0.0, 0.0]);
    let node_id = |key: EntityKey| format!("n:{}", key.0);

    let candidates: Vec<_> = execution
        .arc
        .glides
        .iter()
        .map(|glide| {
            json!({
                "id": node_id(glide.target),
                "predicate": glide.predicate,
                "energy": glide.transfer_energy,
                "position": position(glide.target),
                "strongest": Some(glide.target) == execution.arc.attractor,
            })
        })
        .collect();

    let projection = json!({
        "note": "GENERATED by `cargo run -p universe-e2e --bin neighborhood_projection`. Positions: universe-assets layout engine (force-directed, energy-weighted). Energy: measured:semantic + executed BehaviorBonds. Do not hand-edit; regenerate.",
        "epistemic_status": execution.arc.epistemic_status,
        "start": { "id": node_id(start), "position": position(start) },
        "candidates": candidates,
    });

    let out = repository.join("apps/mind-desktop/src/fixtures/neighborhood-projection.json");
    fs::create_dir_all(out.parent().unwrap())?;
    fs::write(&out, serde_json::to_vec_pretty(&projection)?)?;
    println!(
        "wrote {} ({} candidates, positions from layout engine)",
        out.display(),
        execution.arc.glides.len()
    );
    Ok(())
}
